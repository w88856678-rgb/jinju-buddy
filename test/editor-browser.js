// Independent 4:1 LED rehearsal. BUDDY_PROOF_DIR keeps real Chrome screenshots.
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {existsSync} from 'node:fs';
import {join} from 'node:path';
import {chromium} from 'playwright';
import {extractQuote} from '../server/quotes.js';
import {sourceRef} from '../server/editor-cards.js';
import {causalReading} from '../server/quote-integrity.js';
import {mockCloud, sentence, testApp, until, wire} from './support.js';

const passages = ['如果是昨天的熊浩学长，他可能会说，为什么缺爱的人不太擅长被爱。','因为他太焦急。','太迫切。','以至于听不到雪落下的声音。','爱是自由的渺小，渺小的自由。'];
const out = process.env.BUDDY_PROOF_DIR;
if (out) await mkdir(out,{recursive:true});
const asr = await mockCloud();
const app = await testApp({dialAsr:asr.dial,generate:async(row,previous)=>{
  if (row.body === passages[4]) return row.body;
  if (causalReading([...previous,row])) return extractQuote('unused',row,previous);
  return {status:'waiting'};
}});
const chrome = process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const browser = await chromium.launch({...(existsSync(chrome) ? {executablePath:chrome} : {}),args:['--no-proxy-server']});
try {
  const desk = await browser.newPage({viewport:{width:1440,height:940},deviceScaleFactor:1});
  const stage = await browser.newPage({viewport:{width:1280,height:320},deviceScaleFactor:1});
  await desk.goto(app.url+'/control');
  await stage.goto(app.url+'/stage?look=dark');
  await desk.locator('#workspace').waitFor();
  await stage.waitForFunction(()=>document.querySelector('.scene')?.dataset.kind === 'idle');
  const mic = wire(app,'mic&mode=debate',true);
  await mic.wait(m=>m.type==='ready');
  passages.forEach((body,i)=>asr.connections[0].send({sentences:[sentence(i+1,i===2 ? 6 : 0,body)]}));
  asr.connections[0].send({final:1});
  await until(()=>app.store.segments().length===5 && !app.store.pending().length);
  const mirror = desk.locator('.candidate').filter({has:desk.locator('.candidate-text',{hasText:'爱是自由的渺小'})});
  const mirrorLines = ['爱是自由的渺小','渺小的自由'];
  await mirror.locator('.send-candidate').waitFor();
  assert.deepEqual(await mirror.locator('.display-line').allTextContents(),mirrorLines);
  const held = desk.locator('.candidate').filter({has:desk.getByRole('button',{name:'核对归属'})}).first();
  assert(await held.locator('.send-candidate').isDisabled());
  assert.equal(app.store.screen().version,0);
  await held.getByRole('button',{name:'核对归属'}).click();
  assert.match(await desk.locator('#review-source').innerText(),/他可能会说/);
  await desk.keyboard.press('Escape');
  await mirror.locator('.send-candidate').focus();await desk.keyboard.press('Space');
  await until(async()=>JSON.stringify(await stage.locator('.led-quote span').allTextContents())===JSON.stringify(mirrorLines));
  await mirror.getByRole('button',{name:'编辑',exact:true}).click();
  await mirror.getByRole('textbox').fill('如果不确定，就先问服务对象');
  assert.deepEqual(await mirror.locator('.reading-preview .display-line').allTextContents(),['如果不确定','就先问服务对象']);
  await mirror.getByRole('button',{name:'取消'}).click();
  const field=desk.locator('#live-text');
  await field.evaluate((e)=>{e.focus();e.setSelectionRange(e.value.indexOf('为什么缺爱'),e.value.indexOf('声音。')+'声音。'.length);e.dispatchEvent(new Event('select'));});
  await desk.getByRole('button',{name:'提炼所选'}).focus();await desk.keyboard.press('Enter');
  await desk.locator('#source-review[open]').waitFor();
  assert.match(await desk.locator('#review-source').innerText(),/如果是昨天/);
  await desk.getByRole('button',{name:'确认归属并提炼'}).click();
  const selected=desk.locator('.candidate').filter({has:desk.getByText('选区提炼',{exact:true})});
  await selected.locator('.send-candidate:enabled').waitFor();
  const expected=['缺爱的人为何不太擅长被爱','因为太迫切 听不到雪落声'];
  assert.deepEqual(await selected.locator('.candidate-text span').allTextContents(),expected);
  assert.equal(app.store.screen().version,1);
  await selected.locator('.send-candidate').click();
  await until(async()=>JSON.stringify(await stage.locator('.led-quote span').allTextContents())===JSON.stringify(expected));
  await until(async()=>JSON.stringify(await desk.locator('#preview .led-quote span').allTextContents())===JSON.stringify(expected));
  await stage.reload();await stage.locator('.scene[data-kind=quote]').waitFor();
  assert.deepEqual(await stage.locator('.led-quote span').allTextContents(),expected);
  if(out) {
    await field.evaluate(e=>{e.setSelectionRange(0,0);e.blur();});
    await desk.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
    await until(async()=>await desk.locator('#screen-status').textContent()==='大屏已显示');
    await desk.waitForFunction(()=>!document.querySelector('#preview .led-quote-track').getAnimations().some(a=>a.playState==='running'));
    await desk.screenshot({path:join(out,'彩排控台.png')});
    await stage.screenshot({path:join(out,'彩排投影.png')});
    const native = await browser.newPage({viewport:{width:512,height:128},deviceScaleFactor:1});
    await native.goto(app.url+'/stage?look=dark&native=1');
    await native.locator('.scene[data-kind=quote]').waitFor();
    await native.waitForFunction(()=>Number(getComputedStyle(document.querySelector('.scene')).getPropertyValue('--led-scale'))===1);
    await native.waitForFunction(()=>!document.querySelector('.led-quote-track').getAnimations().length);
    assert.deepEqual(await native.locator('.led-quote span').allTextContents(),expected);
    for(const box of await native.locator('.led-quote span').evaluateAll(lines=>lines.map(n=>n.getBoundingClientRect().toJSON())))
      assert(box.left>=115 && box.right<=501 && box.top>=0 && box.bottom<=128);
    await native.screenshot({path:join(out,'原生512x128.png')});
    await native.close();
  }
  await desk.setViewportSize({width:390,height:844});
  await desk.locator('.live-columns').scrollIntoViewIfNeeded();
  assert(await desk.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  if(out) await desk.locator('.live-columns').screenshot({path:join(out,'窄屏现场发言.png')});
  const change=app.store.segments()[1];
  const response=await app.call('transcript/edit',{id:change.id,rev:change.rev,editVersion:change.editVersion,text:'因为他还没有准备好。',excluded:false});
  assert.equal(response.status,200);await selected.waitFor({state:'detached'});
  assert.deepEqual(app.store.screen().layout.lines,expected);
  assert.equal((await app.call('transcript/extract',{refs:[sourceRef(change)]})).status,409);
  const compactText='甲'.repeat(13)+'\n'+'乙'.repeat(12);
  await desk.locator('#quote').fill(compactText);
  assert(await desk.locator('#manual-send').isDisabled());
  await desk.locator('#manual-compact').check();
  await desk.locator('#manual-send').click();
  await until(()=>app.store.screen().layout?.size===29);
  const smallVersion=app.store.screen().version;
  await app.call('publish',{kind:'idle',op:'manual-after-compact'});
  await desk.locator('#history summary').click();
  const small=desk.locator('.history-item').filter({hasText:'甲'.repeat(13)});
  await small.getByRole('button',{name:'重新展示'}).click();
  await until(()=>app.store.screen().version>smallVersion && app.store.screen().layout?.size===29);
  // A missing film atlas must still leave a readable, acknowledged frame on a fresh stage.
  const fallback = await browser.newPage({viewport:{width:512,height:128}});
  let atlasRequests = 0;
  await fallback.route('**/buddy-film-*x.webp', route => {
    atlasRequests++;
    return route.abort('failed');
  });
  await fallback.goto(app.url+'/stage?look=dark&native=1');
  await until(async () => (await (await app.call('control')).json()).displayed === 2);
  assert(atlasRequests > 0);
  assert.equal(await fallback.locator('.led-buddy').getAttribute('data-motion'), 'still');
  assert.match(await fallback.locator('.led-buddy').evaluate(n => getComputedStyle(n).backgroundImage), /buddy-film-poster/);
  assert.deepEqual(await fallback.locator('.led-quote span').allTextContents(), compactText.split('\n'));
  assert.equal(await fallback.locator('.led-quote').evaluate(n => getComputedStyle(n).fontSize), '29px');
  await fallback.close();
  mic.ws.close();
  console.log('通过：原生两行、转述归属、键盘选择和发送、编辑预览、断线重连、窄屏与校订撤卡。');
} finally { await browser.close();await app.cleanup();await asr.stop(); }
